export const themeOrder = themeIds;

export const defaultAppearancePreferences: Record<ThemeId, ThemeAppearancePreferences> = themeIds.reduce(
  (accumulator, theme) => {
    accumulator[theme] = themeDefinitions[theme].defaults;
    return accumulator;
  },
  {} as Record<ThemeId, ThemeAppearancePreferences>,
);

export function getThemeDefinition(theme: ThemeId) {
  return themeDefinitions[theme];
}
